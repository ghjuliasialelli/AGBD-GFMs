# Geographic generalization of TerraMind+SAR (terramind_tiny) LoRA on FULL AGBD: the same command as
# ../lora/terramind_tiny.sh (the general model, run 20260930_080105_f8cb5c), with dataset=agbd-<mode>-<R>:
#
#   sbatch terramind_tiny_holdout.sh cross    # train + val WITHOUT region R (cross-region)
#   sbatch terramind_tiny_holdout.sh within   # train + val ONLY on region R (within-region)
#   sbatch terramind_tiny_temporal.sh crossyear|withinyear   # train on 2019 / 2020 only, test on 2020 (see the end)
#
# Array task t = REGIONS[t-1]. The dataset configs (../../holdout/make_full_holdout_configs.py) set hold_out_region /
# keep_region for train and for the AGBD-Lite validation set (checkpoint selection), test_region for the test, and
# the normalisation stats of the training rows. Same 120 h budget as the general run (which reached epoch 18):
# a run that times out has its checkpoint__best.pth but no test -- test it with ../../testfull_runs/lora_holdout/.
#
# Before submitting (from the cluster pangaea-bench checkout): the pangaea-bench changes are pulled, and
# AGBD-Lite-continents.npz is in the persistent AGBD-Lite folder. The launcher checks both and the staged files.

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
from staging import STAGE_TRAIN  # noqa: E402

path_script = os.path.dirname(os.path.abspath(__file__))
REGIONS = ['SouthAsia', 'Africa', 'SouthAmerica']
LITE_DIR = '/cluster/work/igp_psr/gsialelli/Data/patches/AGBD-Lite'

text = f"""#!/bin/bash
#SBATCH --nodes=1
#SBATCH --cpus-per-task=24
#SBATCH --time=120:00:00
#SBATCH --output=/cluster/scratch/gsialelli/logs/pangaea-%A_%a.txt
#SBATCH --error=/cluster/scratch/gsialelli/logs/pangaea-%A_%a.txt
#SBATCH --mem-per-cpu=4G
#SBATCH --job-name=pangaea-geo
#SBATCH --gpus=rtx_4090:4
#SBATCH --array=1-{len(REGIONS)}

# GENERATED by benchmark_pangaea/trainfull_runs/lora_holdout/gen.py -- edit that, not this.
# Usage (from the pangaea-bench checkout): sbatch $0 cross|within

MODE=$1
case "$MODE" in cross|within) ;; *) echo "usage: sbatch $0 cross|within"; exit 1 ;; esac
REGIONS=({' '.join(REGIONS)})
REGION=${{REGIONS[$((SLURM_ARRAY_TASK_ID-1))]}}
echo "Mode: $MODE   region: $REGION"

grep -q "test_region" pangaea/datasets/agbd.py || {{ echo "pangaea/datasets/agbd.py has no test_region: pull pangaea-bench first"; exit 1; }}
[ -f configs/dataset/agbd-$MODE-$REGION.yaml ] || {{ echo "configs/dataset/agbd-$MODE-$REGION.yaml missing"; exit 1; }}
[ -f {LITE_DIR}/AGBD-Lite-continents.npz ] || {{ echo "{LITE_DIR}/AGBD-Lite-continents.npz missing"; exit 1; }}

{STAGE_TRAIN}cp {LITE_DIR}/AGBD-Lite-continents.npz ${{TMPDIR}}
for f in AGBD-Lite-val.h5 AGBD-Lite-continents.npz biomes_splits_to_name.pkl tiles_per_region.pkl AEF_overlaps.pkl \\
         data_subset-{{2019,2020}}-v4_{{0..19}}-20.h5; do
    [ -f "${{TMPDIR}}/$f" ] || {{ echo "staging: ${{TMPDIR}}/$f is missing"; exit 1; }}
done

HYDRA_FULL_ERROR=1 torchrun --rdzv-backend=c10d --rdzv-endpoint=localhost:0 --nnodes=1 --nproc_per_node=4 pangaea/run.py  --config-name=train  dataset=agbd-$MODE-$REGION  encoder=terramind_tiny  decoder=reg_upernet  preprocessing=reg_resize  criterion=mse  task=regression finetune=true lora=default batch_size=32 num_workers=6 test_num_workers=6 test_batch_size=32 use_wandb=True task.trainer.eval_interval=0.25 dataset.root_path_cluster=${{TMPDIR}} task.trainer.log_interval=100
"""

out = os.path.join(path_script, 'terramind_tiny_holdout.sh')
with open(out, 'w') as f: f.write(text)
print(f'Wrote {out}\nsbatch {out} cross\nsbatch {out} within')

# Temporal generalization (one job each, test on 2020): dataset=agbd-crossyear (train 2019) / agbd-withinyear (train 2020).
# crossyear validates on the full 2019 val split (610k rows, vs 104k for AGBD-Lite-val), so once per epoch
# (eval_interval=1) instead of 4 times; withinyear keeps the general run's eval_interval=0.25 on AGBD-Lite-val.
text_t = f"""#!/bin/bash
#SBATCH --nodes=1
#SBATCH --cpus-per-task=24
#SBATCH --time=120:00:00
#SBATCH --output=/cluster/scratch/gsialelli/logs/pangaea-%A.txt
#SBATCH --error=/cluster/scratch/gsialelli/logs/pangaea-%A.txt
#SBATCH --mem-per-cpu=4G
#SBATCH --job-name=pangaea-year
#SBATCH --gpus=rtx_4090:4

# GENERATED by benchmark_pangaea/trainfull_runs/lora_holdout/gen.py -- edit that, not this.
# Usage (from the pangaea-bench checkout): sbatch $0 crossyear|withinyear

MODE=$1
case "$MODE" in crossyear) EVAL=1 ;; withinyear) EVAL=0.25 ;; *) echo "usage: sbatch $0 crossyear|withinyear"; exit 1 ;; esac
echo "Mode: $MODE   eval_interval: $EVAL"

grep -q "test_years" pangaea/datasets/agbd.py || {{ echo "pangaea/datasets/agbd.py has no test_years: pull pangaea-bench first"; exit 1; }}
[ -f configs/dataset/agbd-$MODE.yaml ] || {{ echo "configs/dataset/agbd-$MODE.yaml missing"; exit 1; }}

{STAGE_TRAIN}for f in AGBD-Lite-val.h5 biomes_splits_to_name.pkl tiles_per_region.pkl AEF_overlaps.pkl \\
         data_subset-{{2019,2020}}-v4_{{0..19}}-20.h5; do
    [ -f "${{TMPDIR}}/$f" ] || {{ echo "staging: ${{TMPDIR}}/$f is missing"; exit 1; }}
done

HYDRA_FULL_ERROR=1 torchrun --rdzv-backend=c10d --rdzv-endpoint=localhost:0 --nnodes=1 --nproc_per_node=4 pangaea/run.py  --config-name=train  dataset=agbd-$MODE  encoder=terramind_tiny  decoder=reg_upernet  preprocessing=reg_resize  criterion=mse  task=regression finetune=true lora=default batch_size=32 num_workers=6 test_num_workers=6 test_batch_size=32 use_wandb=True task.trainer.eval_interval=$EVAL dataset.root_path_cluster=${{TMPDIR}} task.trainer.log_interval=100
"""
out_t = os.path.join(path_script, 'terramind_tiny_temporal.sh')
with open(out_t, 'w') as f: f.write(text_t)
print(f'Wrote {out_t}\nsbatch {out_t} crossyear\nsbatch {out_t} withinyear')
