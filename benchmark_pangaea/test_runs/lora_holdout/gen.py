# Regional AGBD-Lite test of TerraMind+SAR LoRA, for the leave-one-region-out comparison. One launcher, two modes,
# array task t = REGIONS[t-1]; both modes test on the AGBD-Lite-test rows of that region only:
#
#   sbatch terramind_tiny_regions.sh holdout   # the model trained WITHOUT the region (../../configs/lora_holdout.txt, line t)
#   sbatch terramind_tiny_regions.sh fixed     # the in-distribution baseline (BASELINE), same footprints
#
# Both go through the SAME code path: the region is set with test_overrides.dataset.test_region (redundant for the
# held-out runs, whose config already has it), and each model keeps the normalisation stats it was trained with
# (saved in its config.yaml). AGBD_DUMP_H5 writes the per-sample (prediction, label) pairs to
# /cluster/scratch/gsialelli/agbd_dumps/<run>_<R>_lite_test.h5 -- compute the RMSE from those: the logged RMSE is
# sqrt(mean of per-batch MSE), which weights a short last batch like a full one.
#
# The training jobs already end with this test (holdout mode), so `holdout` is only needed for the dumps or a rerun.
# Each test runs in a shadow directory <run>_test-<R> (symlinks to the run's config + checkpoints), with wandb off,
# so neither the run directory nor its wandb run is modified.
# Regenerate after filling ../../configs/lora_holdout.txt; the `holdout` mode refuses placeholder names.

import os

path_script = os.path.dirname(os.path.abspath(__file__))
configs_file = os.path.join(path_script, '..', '..', 'configs', 'lora_holdout.txt')

REGIONS = ['SouthAsia', 'Africa', 'SouthAmerica']
BASELINE = '20260922_172445_017c55_terramind_tiny_lora_reg_upernet_agbdlite' # ../../configs/lora.txt
DATA_DIR = '/cluster/scratch/gsialelli'
DUMP_DIR = '/cluster/scratch/gsialelli/agbd_dumps'


def read_configs(path):
    with open(path, 'r') as f:
        return [ln.strip() for ln in f if ln.strip() and not ln.lstrip().startswith('#')]


runs = read_configs(configs_file)
assert len(runs) == len(REGIONS), f'{configs_file}: expected {len(REGIONS)} run names (one per region), got {len(runs)}'
for region, run in zip(REGIONS, runs):
    assert run.startswith('RUN_DIR_') or run.endswith(f'_agbdlite-holdout-{region}'), \
        f'{configs_file}: line for {region} is {run!r}, which is not a {region} hold-out run (order: {REGIONS})'

text = f"""#!/bin/bash
#SBATCH --nodes=1
#SBATCH --cpus-per-task=8
#SBATCH --time=24:00:00
#SBATCH --output=/cluster/scratch/gsialelli/logs/pangaea-%A_%a.txt
#SBATCH --error=/cluster/scratch/gsialelli/logs/pangaea-%A_%a.txt
#SBATCH --mem-per-cpu=8G
#SBATCH --job-name=pangaea-regions
#SBATCH --gpus=rtx_4090:1
#SBATCH --array=1-{len(REGIONS)}

# GENERATED by benchmark_pangaea/test_runs/lora_holdout/gen.py -- edit that, not this.
# Usage (from the pangaea-bench checkout): sbatch $0 holdout|fixed

MODE=$1
REGIONS=({' '.join(REGIONS)})
HOLDOUT_RUNS=({' '.join(runs)})
REGION=${{REGIONS[$((SLURM_ARRAY_TASK_ID-1))]}}
case "$MODE" in
    holdout) CKPT=${{HOLDOUT_RUNS[$((SLURM_ARRAY_TASK_ID-1))]}} ;;
    fixed)   CKPT={BASELINE} ;;
    *) echo "usage: sbatch $0 holdout|fixed"; exit 1 ;;
esac
case "$CKPT" in RUN_DIR_*) echo "configs/lora_holdout.txt still has the placeholder $CKPT: fill it and rerun gen.py"; exit 1 ;; esac
echo "Mode: $MODE   region: $REGION   checkpoint: $CKPT"

grep -q "test_region" pangaea/datasets/agbdlite.py || {{ echo "pangaea/datasets/agbdlite.py has no region selection: sync pangaea-bench first"; exit 1; }}
[ -f {DATA_DIR}/AGBD-Lite-continents.npz ] || {{ echo "{DATA_DIR}/AGBD-Lite-continents.npz missing"; exit 1; }}
[ -d "$CKPT" ] || {{ echo "no run directory $CKPT here"; exit 1; }}
[ -f "$CKPT/configs/config.yaml" ] || {{ echo "$CKPT/configs/config.yaml missing"; exit 1; }}
ls "$CKPT"/*_best.pth > /dev/null 2>&1 || {{ echo "no *_best.pth in $CKPT"; exit 1; }}

# Test in a SHADOW run directory: run.py test mode writes <ckpt_dir>/test.log-<rank> with mode "w", which would
# overwrite the run's own (global Lite) test log -- and the 3 array tasks would overwrite each other. The shadow
# directory only symlinks the config and the checkpoints, so the run directory itself is never written to.
SHADOW=${{CKPT}}_test-${{REGION}}
mkdir -p "$SHADOW"
ln -sfn "$(realpath "$CKPT/configs")" "$SHADOW/configs"
for f in "$CKPT"/*.pth; do ln -sfn "$(realpath "$f")" "$SHADOW/$(basename "$f")"; done
echo "Shadow run directory: $SHADOW"

# wandb OFF: the saved config has use_wandb=true and wandb_run_id = the TRAINING run's id, so run.py would resume
# that wandb run and log this regional score as its test_RMSE, replacing the global one in the run summary.
AGBD_DUMP_H5={DUMP_DIR}/${{CKPT}}_${{REGION}}_lite_test.h5 torchrun --rdzv-backend=c10d --rdzv-endpoint=localhost:0 --nnodes=1 --nproc_per_node=1 pangaea/run.py --config-name=test ckpt_dir=$SHADOW ++test_overrides.dataset.test_region=$REGION ++test_overrides.use_wandb=false ++test_overrides.task.trainer.use_wandb=false ++test_overrides.task.evaluator.use_wandb=false
"""

out = os.path.join(path_script, 'terramind_tiny_regions.sh')
with open(out, 'w') as f: f.write(text)
print(f'Wrote {out}')
print(f'sbatch {out} fixed')
if any(r.startswith('RUN_DIR_') for r in runs):
    print(f'(holdout mode needs the run names in {os.path.normpath(configs_file)}; regenerate after filling it)')
else:
    print(f'sbatch {out} holdout')
