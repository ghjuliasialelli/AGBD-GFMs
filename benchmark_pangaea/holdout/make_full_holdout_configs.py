"""
Dataset configs for the full-AGBD geographic and temporal generalization runs of TerraMind+SAR LoRA
(../trainfull_runs/lora_holdout/):

    configs/dataset/agbd-cross-<R>.yaml    train + val WITHOUT region R (cross-region), test on R
    configs/dataset/agbd-within-<R>.yaml   train + val ONLY on region R (within-region), test on R
    configs/dataset/agbd-crossyear.yaml    train 2019 only, test 2020   (see the temporal block at the end)
    configs/dataset/agbd-withinyear.yaml   train 2020 only, test 2020

`agbd` + hold_out_region / keep_region / test_region + the normalisation stats of the training rows. NormalizeMinMax
only uses data_min / data_max; mean / std are written for completeness. Same sources as configs/dataset/agbd.yaml:
- optical: model/'s AGBD_statistics_2019-2020_*.pkl (agbd.yaml's optical stats ARE ..._global.pkl, asserted below);
  the region files are the ones the fcn_film geographic runs of the paper used.
- sar: agbd.yaml takes its clip bounds from AGBD-Lite train (p0.1 / p99.9 rounded outwards), so the region bounds
  come from the same Lite histograms (AGBD-Lite-train-histograms.npz, compute_lite_holdout_stats.py): R excluded for
  cross-region, R only for within-region. sar mean / std are on Lite too (agbd.yaml's are on full; unused).
Exits before writing anything unless the global pkl reproduces agbd.yaml's optical stats exactly and the global Lite
histograms reproduce its SAR bounds.

Run: .venv/bin/python benchmark_pangaea/holdout/make_full_holdout_configs.py
"""
import argparse, os, pickle, sys
from os.path import join, dirname, abspath

import numpy as np
import yaml

sys.path.insert(0, dirname(abspath(__file__)))
from compute_lite_holdout_stats import CONTINENTS, HOLDOUT, S2_BANDS, stats_from_hist, fmt

FNAME_ORDER = ['Europe', 'SouthAsia', 'Australasia', 'Africa', 'NorthAmerica', 'SouthAmerica'] # model/ stats file names
PANGAEA_NAME = {'SouthAsia': 'South Asia', 'Africa': 'Africa', 'SouthAmerica': 'South America'} # agbd.py keys


def pkl_optical(path) :
    with open(path, 'rb') as f : s2 = pickle.load(f)['S2_bands']
    return {k : [float(s2[b][k]) for b in S2_BANDS] for k in ('mean', 'std', 'min', 'max')}


if __name__ == '__main__' :
    p = argparse.ArgumentParser()
    p.add_argument('--stats_dir', default = '/scratch3/gsialelli/patches', help = 'AGBD_statistics_2019-2020_*.pkl')
    p.add_argument('--hist', default = '/scratch3/gsialelli/patches/AGBD-Lite/AGBD-Lite-train-histograms.npz')
    p.add_argument('--pangaea_dir', default = '/scratch3/gsialelli/pangaea-bench')
    args = p.parse_args()

    with open(join(args.pangaea_dir, 'configs', 'dataset', 'agbd.yaml')) as f : ref = yaml.safe_load(f)
    with np.load(args.hist) as z :
        assert [str(c) for c in z['names']] == CONTINENTS, z['names']
        s2, sar = z['s2'], z['sar']

    # Gate
    g = pkl_optical(join(args.stats_dir, 'AGBD_statistics_2019-2020_global.pkl'))
    ok = all(np.array_equal(np.float32(g[k]), np.float32(ref[f'data_{k}']['optical'])) for k in g)
    glite = stats_from_hist(s2.sum(0), sar.sum(0))
    ok &= glite['data_min']['sar'] == ref['data_min']['sar'] and glite['data_max']['sar'] == ref['data_max']['sar']
    if not ok : sys.exit('agbd.yaml is not reproduced by the global pkl (optical) / Lite histograms (sar bounds); nothing written.')
    print('Gate passed: global pkl == agbd.yaml optical stats; Lite SAR bounds == agbd.yaml SAR bounds.')

    for r in HOLDOUT :
        ci = CONTINENTS.index(r)
        others = [i for i in range(len(CONTINENTS)) if i != ci]
        kept = '-'.join(c for c in FNAME_ORDER if c != r)
        for kind, keep, pkl, sar_h in [('cross', False, kept, sar[others].sum(0)), ('within', True, r, sar[ci])] :
            opt = pkl_optical(join(args.stats_dir, f'AGBD_statistics_2019-2020_{pkl}.pkl'))
            st = stats_from_hist(s2.sum(0), sar_h) # only the sar part is used
            what = f'WITHOUT {r} (cross-region)' if kind == 'cross' else f'ONLY {r} (within-region)'
            text = f"""# GENERATED by AGBD-GFMs/benchmark_pangaea/holdout/make_full_holdout_configs.py -- do not edit by hand.
# Full AGBD, train + val (AGBD-Lite-val, eval_lite) {what}; test on {r} only (tiles, drop_overlaps).
# optical stats: AGBD_statistics_2019-2020_{pkl}.pkl (model/); sar: AGBD-Lite train histograms, {what}.
defaults:
  - agbd
  - _self_

hold_out_region: {PANGAEA_NAME[r]}
keep_region: {str(keep)}
test_region: {PANGAEA_NAME[r]}

data_mean:
  optical: {fmt(opt['mean'])}
  sar: {fmt(st['data_mean']['sar'])}

data_std:
  optical: {fmt(opt['std'])}
  sar: {fmt(st['data_std']['sar'])}

data_min:
  optical: {fmt(opt['min'])}
  sar: {fmt(st['data_min']['sar'])}

data_max:
  optical: {fmt(opt['max'])}
  sar: {fmt(st['data_max']['sar'])}
"""
            out = join(args.pangaea_dir, 'configs', 'dataset', f'agbd-{kind}-{r}.yaml')
            with open(out, 'w') as f : f.write(text)
            print(f'{out}: optical max {fmt(opt["max"])}  sar [{st["data_min"]["sar"]}, {st["data_max"]["sar"]}]')

    # Temporal generalization (test always on 2020, as the paper's temporal table) ---------------------------------
    #   agbd-crossyear.yaml   train 2019 only; val on the FULL 2019 val split (AGBD-Lite-val is 2020-only data, i.e. the
    #                         target year); optical: AGBD_statistics_2019_global.pkl; sar: full 2019 train histograms
    #                         (full_year_sar_hist.py; agbd.yaml's Lite bounds are 2020 data)
    #   agbd-withinyear.yaml  train 2020 only; val on AGBD-Lite-val (2020, as the general run);
    #                         optical: AGBD_statistics_2020_global.pkl; sar: AGBD-Lite train (2020) = agbd.yaml's bounds
    # The all-years column is the general run, tested on 2020 (++test_overrides.dataset.test_years=[2020]).
    hist19 = join(args.stats_dir, 'AGBD-train-2019-sar-histograms.npz')
    for kind, year, eval_lite, sar_h, sar_src in [('crossyear', 2019, False, hist19, 'full 2019 train histograms (full_year_sar_hist.py)'),
                                                 ('withinyear', 2020, True, None, 'AGBD-Lite train histograms (2020 data; = agbd.yaml bounds)')] :
        if sar_h is not None :
            if not os.path.exists(sar_h) : print(f'SKIP agbd-{kind}.yaml: {sar_h} missing (run full_year_sar_hist.py --year {year})'); continue
            with np.load(sar_h) as z : assert int(z['year']) == year; h = z['sar']
        else : h = sar.sum(0)
        opt = pkl_optical(join(args.stats_dir, f'AGBD_statistics_{year}_global.pkl'))
        st = stats_from_hist(s2.sum(0), h) # only the sar part is used
        text = f"""# GENERATED by AGBD-GFMs/benchmark_pangaea/holdout/make_full_holdout_configs.py -- do not edit by hand.
# Full AGBD, train on {year} only, val on {'AGBD-Lite-val (2020)' if eval_lite else f'the full {year} val split'}; test on 2020 only (tiles, drop_overlaps).
# optical stats: AGBD_statistics_{year}_global.pkl (model/); sar: {sar_src}.
defaults:
  - agbd
  - _self_

years: [{year}]
test_years: [2020]
eval_lite: {str(eval_lite)}

data_mean:
  optical: {fmt(opt['mean'])}
  sar: {fmt(st['data_mean']['sar'])}

data_std:
  optical: {fmt(opt['std'])}
  sar: {fmt(st['data_std']['sar'])}

data_min:
  optical: {fmt(opt['min'])}
  sar: {fmt(st['data_min']['sar'])}

data_max:
  optical: {fmt(opt['max'])}
  sar: {fmt(st['data_max']['sar'])}
"""
        out = join(args.pangaea_dir, 'configs', 'dataset', f'agbd-{kind}.yaml')
        with open(out, 'w') as f : f.write(text)
        print(f'{out}: optical max {fmt(opt["max"])}  sar [{st["data_min"]["sar"]}, {st["data_max"]["sar"]}]')
